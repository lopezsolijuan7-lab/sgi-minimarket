CREATE TABLE IF NOT EXISTS public.compras (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id bigint NOT NULL REFERENCES public.proveedores(id),
  sucursal_id bigint NOT NULL REFERENCES public.sucursales(id),
  usuario_id uuid NOT NULL REFERENCES public.usuarios(id),
  fecha_compra timestamptz NOT NULL DEFAULT now(),
  total numeric(12,2) NOT NULL DEFAULT 0 CHECK(total >= 0),
  estado varchar(20) NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente','recibida','anulada')),
  observaciones text
);
CREATE TABLE IF NOT EXISTS public.detalle_compras (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id bigint NOT NULL REFERENCES public.compras(id),
  producto_id bigint NOT NULL REFERENCES public.productos(id),
  cantidad integer NOT NULL CHECK(cantidad > 0),
  costo_unitario numeric(12,2) NOT NULL CHECK(costo_unitario >= 0),
  subtotal numeric(12,2) GENERATED ALWAYS AS (cantidad*costo_unitario) STORED
);
CREATE TABLE IF NOT EXISTS public.recepciones_compra (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id bigint NOT NULL REFERENCES public.compras(id),
  usuario_id uuid NOT NULL REFERENCES public.usuarios(id),
  operacion_id uuid NOT NULL UNIQUE,
  fecha_recepcion timestamptz NOT NULL DEFAULT now(),
  observaciones text
);
CREATE TABLE IF NOT EXISTS public.detalle_recepciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recepcion_id bigint NOT NULL REFERENCES public.recepciones_compra(id),
  detalle_compra_id bigint NOT NULL REFERENCES public.detalle_compras(id),
  cantidad_recibida integer NOT NULL DEFAULT 0 CHECK(cantidad_recibida >= 0),
  cantidad_danada integer NOT NULL DEFAULT 0 CHECK(cantidad_danada >= 0),
  cantidad_faltante integer NOT NULL DEFAULT 0 CHECK(cantidad_faltante >= 0),
  CONSTRAINT detalle_recepcion_valida CHECK(cantidad_recibida+cantidad_danada+cantidad_faltante > 0),
  CONSTRAINT detalle_recepcion_unico UNIQUE(recepcion_id,detalle_compra_id)
);


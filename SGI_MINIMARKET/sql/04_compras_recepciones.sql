-- Registrar orden completa de manera atomica; admin activo solamente.
CREATE OR REPLACE FUNCTION public.sgi_crear_compra(
  p_proveedor_id bigint, p_sucursal_id bigint, p_observaciones text, p_items jsonb
) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_user uuid := (SELECT auth.uid()); v_compra bigint; v_item record;
        v_total numeric(12,2) := 0;
BEGIN
  IF v_user IS NULL OR NOT EXISTS(
    SELECT 1 FROM public.usuarios u WHERE u.id=v_user AND u.activo AND u.rol='administrador'
  ) THEN RAISE EXCEPTION 'Solo un administrador activo puede crear compras'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.proveedores WHERE id=p_proveedor_id AND activo)
  THEN RAISE EXCEPTION 'Proveedor inexistente o inactivo'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.sucursales WHERE id=p_sucursal_id AND activo)
  THEN RAISE EXCEPTION 'Sucursal inexistente o inactiva'; END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 100
  THEN RAISE EXCEPTION 'Indica entre 1 y 100 productos'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_items)
      AS j(producto_id bigint,cantidad integer,costo_unitario numeric)
    GROUP BY j.producto_id HAVING j.producto_id IS NULL OR count(*) > 1
  ) THEN RAISE EXCEPTION 'Productos duplicados o invalidos'; END IF;
  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items)
      AS j(producto_id bigint,cantidad integer,costo_unitario numeric) LOOP
    IF v_item.cantidad IS NULL OR v_item.cantidad < 1 OR v_item.cantidad > 1000000
      OR v_item.costo_unitario IS NULL OR v_item.costo_unitario < 0
      OR v_item.costo_unitario > 99999999.99
    THEN RAISE EXCEPTION 'Cantidad/costo fuera de rango'; END IF;
    IF NOT EXISTS(SELECT 1 FROM public.productos WHERE id=v_item.producto_id AND activo)
    THEN RAISE EXCEPTION 'Producto inexistente o inactivo'; END IF;
    v_total := v_total + round(v_item.cantidad * v_item.costo_unitario,2);
  END LOOP;
  IF v_total > 9999999999.99 THEN RAISE EXCEPTION 'Total demasiado alto'; END IF;
  INSERT INTO public.compras(proveedor_id,sucursal_id,usuario_id,total,estado,observaciones)
  VALUES(p_proveedor_id,p_sucursal_id,v_user,v_total,'pendiente',
         nullif(left(btrim(coalesce(p_observaciones,'')),500),'')) RETURNING id INTO v_compra;
  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items)
      AS j(producto_id bigint,cantidad integer,costo_unitario numeric) LOOP
    INSERT INTO public.detalle_compras(compra_id,producto_id,cantidad,costo_unitario)
    VALUES(v_compra,v_item.producto_id,v_item.cantidad,round(v_item.costo_unitario,2));
  END LOOP;
  RETURN v_compra;
END;
$$;

-- Recibir cantidades correctas/dañadas; NO duplica entregas con el mismo UUID.
-- Bloquea la compra antes de contar cantidades; la transaccion es atomica.
CREATE OR REPLACE FUNCTION public.sgi_confirmar_recepcion(
  p_compra_id bigint, p_operacion_id uuid, p_items jsonb, p_observaciones text
) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_user uuid := (SELECT auth.uid()); v_compra public.compras%ROWTYPE;
        v_item record; v_detalle public.detalle_compras%ROWTYPE;
        v_anterior integer; v_nuevo integer; v_recibido integer;
        v_recepcion bigint; v_existente record;
BEGIN
  IF v_user IS NULL OR p_operacion_id IS NULL THEN RAISE EXCEPTION 'Sesion u operacion invalida'; END IF;
  SELECT * INTO v_compra FROM public.compras WHERE id=p_compra_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Compra inexistente'; END IF;
  IF NOT EXISTS(
    SELECT 1 FROM public.usuarios u WHERE u.id=v_user AND u.activo
      AND (u.rol='administrador' OR (u.rol='empleado' AND u.sucursal_id=v_compra.sucursal_id))
  ) THEN RAISE EXCEPTION 'No autorizado en esta sucursal'; END IF;
  SELECT id,compra_id INTO v_existente FROM public.recepciones_compra
    WHERE operacion_id=p_operacion_id;
  IF FOUND THEN
    IF v_existente.compra_id <> p_compra_id THEN RAISE EXCEPTION 'Operacion pertenece a otra compra'; END IF;
    RETURN v_existente.id;
  END IF;
  IF v_compra.estado <> 'pendiente' THEN RAISE EXCEPTION 'La compra ya esta cerrada o anulada'; END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
    OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 100
  THEN RAISE EXCEPTION 'Debe indicar los productos recibidos'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_items)
      AS j(detalle_compra_id bigint,cantidad_recibida integer,cantidad_danada integer,cantidad_faltante integer)
    GROUP BY j.detalle_compra_id HAVING j.detalle_compra_id IS NULL OR count(*) > 1
  ) THEN RAISE EXCEPTION 'Detalle duplicado o invalido'; END IF;
  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items)
      AS j(detalle_compra_id bigint,cantidad_recibida integer,cantidad_danada integer,cantidad_faltante integer) LOOP
    IF v_item.cantidad_recibida IS NULL OR v_item.cantidad_danada IS NULL
       OR v_item.cantidad_faltante IS NULL
       OR v_item.cantidad_recibida < 0 OR v_item.cantidad_danada < 0
       OR v_item.cantidad_faltante < 0
       OR (v_item.cantidad_recibida + v_item.cantidad_danada + v_item.cantidad_faltante) < 1
    THEN RAISE EXCEPTION 'Cantidades invalidas'; END IF;
    SELECT * INTO v_detalle FROM public.detalle_compras
      WHERE id=v_item.detalle_compra_id AND compra_id=p_compra_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Detalle ajeno a esta compra'; END IF;
    SELECT coalesce(sum(r.cantidad_recibida + r.cantidad_danada),0)::integer
      INTO v_recibido FROM public.detalle_recepciones r WHERE r.detalle_compra_id=v_detalle.id;
    IF v_recibido + v_item.cantidad_recibida + v_item.cantidad_danada
       + v_item.cantidad_faltante > v_detalle.cantidad
    THEN RAISE EXCEPTION 'La cantidad supera el saldo del pedido'; END IF;
  END LOOP;
  INSERT INTO public.recepciones_compra(compra_id,usuario_id,operacion_id,observaciones)
  VALUES(p_compra_id,v_user,p_operacion_id,
         nullif(left(btrim(coalesce(p_observaciones,'')),500),'')) RETURNING id INTO v_recepcion;
  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items)
      AS j(detalle_compra_id bigint,cantidad_recibida integer,cantidad_danada integer,cantidad_faltante integer) LOOP
    SELECT * INTO v_detalle FROM public.detalle_compras WHERE id=v_item.detalle_compra_id;
    INSERT INTO public.detalle_recepciones(
      recepcion_id,detalle_compra_id,cantidad_recibida,cantidad_danada,cantidad_faltante
    ) VALUES(v_recepcion,v_item.detalle_compra_id,v_item.cantidad_recibida,v_item.cantidad_danada,v_item.cantidad_faltante);
    IF v_item.cantidad_recibida > 0 THEN
      -- Garantizar que un producto sin fila previa tambien pueda recibirse.
      INSERT INTO public.inventarios(producto_id,sucursal_id,stock,stock_minimo)
      VALUES(v_detalle.producto_id,v_compra.sucursal_id,0,5)
      ON CONFLICT(producto_id,sucursal_id) DO NOTHING;
      SELECT stock INTO v_anterior FROM public.inventarios
      WHERE producto_id=v_detalle.producto_id AND sucursal_id=v_compra.sucursal_id FOR UPDATE;
      v_nuevo := v_anterior + v_item.cantidad_recibida;
      UPDATE public.inventarios SET stock=v_nuevo,actualizado_en=now()
      WHERE producto_id=v_detalle.producto_id AND sucursal_id=v_compra.sucursal_id;
      INSERT INTO public.movimientos_inventario(
        producto_id,sucursal_id,tipo,cantidad,stock_anterior,stock_nuevo,motivo,usuario_id
      ) VALUES (
        v_detalle.producto_id,v_compra.sucursal_id,'entrada',v_item.cantidad_recibida,
        v_anterior,v_nuevo,left('Recepcion compra #'||p_compra_id||' / entrega #'||v_recepcion,200),v_user
      );
    END IF;
  END LOOP;
  IF NOT EXISTS(
    SELECT 1 FROM public.detalle_compras d WHERE d.compra_id=p_compra_id
      AND d.cantidad > (
        SELECT coalesce(sum(r.cantidad_recibida + r.cantidad_danada),0)
        FROM public.detalle_recepciones r WHERE r.detalle_compra_id=d.id
      )
  ) THEN UPDATE public.compras SET estado='recibida' WHERE id=p_compra_id; END IF;
  RETURN v_recepcion;
END;
$$;

